"""Coordinate the existing Gemini adapter's cache across episode workers.

The adapter and its input fingerprint stay unchanged, so existing audio runs can
still resume. Shared cache entries must never be regenerated by two workers.
"""
from .speech import GeminiSpeech, speech_settings
from .storage import digest, file_hash, file_lock, write_json


class LockedGeminiSpeech(GeminiSpeech):
    def synthesize(self, text, voice, language, cache):
        key = digest(speech_settings(text, voice, language))
        with file_lock(cache / "locks" / (key + ".lock"), timeout=self.timeout + 30):
            # Recursive splits use this method as well. Each child is shorter,
            # so lock dependencies cannot form a cycle.
            return super().synthesize(text, voice, language, cache)


def run_parallel_gemini_tts(config, script, root, work, choice, api_key=None):
    engine = LockedGeminiSpeech(api_key, timeout=config.runtime.tts_timeout_seconds)
    rows, paths = [], []
    for segment in script.segments:
        write_json(work / "tts_progress.json", {"completed_segments": len(rows),
            "total_segments": len(script.segments), "current_segment": segment.segment_id})
        voice = choice.voices[segment.speaker_id]
        path = engine.synthesize(segment.text, voice, config.language, root / "cache/audio/gemini")
        paths.append(path)
        rows.append({"segment_id": segment.segment_id, "path": path.relative_to(root / "cache/audio").as_posix(),
            "sha256": file_hash(path), "settings": speech_settings(segment.text, voice, config.language)})
    write_json(work / "tts_report.json", {"segments": rows})
    write_json(work / "tts_progress.json", {"completed_segments": len(rows), "total_segments": len(rows)})
    return paths
